"""Methods used to interact with Twitch's API"""

from dataclasses import dataclass
from typing import Optional

import requests

from twitchrewards.config import settings
from twitchrewards.twitch.user import User

TWITCH_GET_USER_URL = "https://api.twitch.tv/helix/users"
TWITCH_ACCESS_TOKEN_URL = "https://id.twitch.tv/oauth2/token"


@dataclass
class TwitchResponse:
    """Represents a response from the Twitch API"""


@dataclass
class TwitchBadResponse(TwitchResponse):
    """Represents a failed response from Twitch API"""


@dataclass
class TwitchUserResponse(TwitchResponse):
    """Wraps the user from a successful Twitch API response"""

    user: User


def get_user(twitch_token: str) -> TwitchResponse:
    """
    Return the Twitch name of the user that owns the given token

    Parameters:
        twitch_token (str): Twitch access token to access its API.

    Returns:
        TwitchResponse: Whether the call succeeded or not, and it's content in case of success.
    """
    r = requests.get(
        TWITCH_GET_USER_URL,
        headers={
            "Authorization": f"Bearer {twitch_token}",
            "Client-Id": settings.TWITCH_APP_CLIENT_ID,
        },
        timeout=30,
    )
    if r.status_code != 200:
        return TwitchBadResponse()

    name = r.json()["data"][0]["display_name"]
    profile_image_url = r.json()["data"][0]["profile_image_url"]
    return TwitchUserResponse(User(name, profile_image_url))


def get_access_token(code: str) -> Optional[str]:
    """
    Return the access token for the Twitch API.

    Parameters:
        code (str): Code generated by Twitch to generate the access token.

    Returns:
        Optional[str]: Whether the call succeeded or not, and the access token in case of success.
    """
    # Build redirect_uri omitting default ports (80 for HTTP, 443 for HTTPS)
    # When behind Cloudflare Tunnel/reverse proxy, external port is always 443 (HTTPS) or 80 (HTTP)
    from urllib.parse import urlparse
    parsed = urlparse(settings.APP_HOST)
    # Use standard ports for redirect_uri since Cloudflare terminates SSL on 443
    if parsed.scheme == "https":
        redirect_uri = f"{settings.APP_HOST}/token"  # port 443 omitted
    elif parsed.scheme == "http":
        redirect_uri = f"{settings.APP_HOST}/token"  # port 80 omitted
    else:
        redirect_uri = f"{settings.APP_HOST}:{settings.APP_PORT}/token"

    print(f"DEBUG: Requesting Twitch token with redirect_uri={redirect_uri}, code={code[:10]}...")
    
    r = requests.post(
        TWITCH_ACCESS_TOKEN_URL,
        data={
            "code": code,
            "client_id": settings.TWITCH_APP_CLIENT_ID,
            "client_secret": settings.TWITCH_APP_CLIENT_SECRET,
            "grant_type": "authorization_code",
            "redirect_uri": redirect_uri,
        },
        timeout=30,
    )
    print(f"DEBUG: Twitch response status={r.status_code}, body={r.text}")
    if r.status_code != 200:
        return None

    return r.json()["access_token"]
